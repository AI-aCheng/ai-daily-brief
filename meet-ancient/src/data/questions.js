/**
 * 随机抽题引擎 (保证标签覆盖均衡 + 注意力检测题必含)
 * @param {Array} all 全量题库
 * @param {Number} count 抽取数量 (默认30)
 * @returns {Array} 抽出的题目 (打乱顺序)
 */
export function pickQuestions(all, count = 30) {
  const attention = all.filter((q) => q.attention)
  const normal = all.filter((q) => !q.attention)
  const need = Math.max(0, count - attention.length)
  if (need >= normal.length) return shuffle([...attention, ...normal])

  // 多次随机采样, 选标签覆盖最均衡的一组 (方差最小)
  let best = null
  let bestScore = Infinity
  for (let i = 0; i < 100; i++) {
    const picked = shuffle(normal).slice(0, need)
    const score = coverageScore(picked)
    if (score < bestScore) {
      bestScore = score
      best = picked
    }
  }
  return shuffle([...attention, ...best])
}

function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

function coverageScore(picked) {
  // 标签覆盖均衡度: 每个标签被覆盖的题数, 方差越小越均衡
  const cnt = {}
  for (const q of picked) {
    for (const o of q.options) {
      for (const t of Object.keys(o.tags)) cnt[t] = (cnt[t] || 0) + 1
    }
  }
  const vals = Object.values(cnt)
  if (vals.length < 25) return Infinity // 覆盖的标签种类太少则弃
  const mean = vals.reduce((a, b) => a + b, 0) / vals.length
  return vals.reduce((a, b) => a + (b - mean) ** 2, 0) / vals.length
}
